/**
 * Словарь типов мероприятий. Отдельный модуль, а не часть `data.ts`, по технической причине:
 * `data.ts` импортирует собранный JSON по алиасу `@/src/...`, который понимают Next и tsc, но не
 * голый Node, — а `filters.ts` покрыт юнит-тестами, которые запускаются именно голым Node.
 * Значение, затащенное в отбор из `data.ts`, уронило бы весь файл тестов на импорте.
 *
 * Сами значения — из портального `EventType`: календарь типологию переносит, а не изобретает.
 */
export type EventKind = 'tournament' | 'festival' | 'camp' | 'seminar' | 'lecture' | 'other';

/**
 * Подписи — те же слова, что в портальном `KIND_LABEL`, в единственном числе и с маленькой
 * буквы: они встают в строку под названием («1–14 августа · лагерь») и в список фильтра.
 */
export const KIND_LABEL: Record<EventKind, string> = {
  tournament: 'турнир',
  festival: 'фестиваль',
  camp: 'лагерь',
  seminar: 'семинар',
  lecture: 'лекция',
  other: 'другое',
};

/** Порядок в фильтре — тот же, что в `TYPE_ORDER` сборки: сперва то, чего в календаре больше. */
export const KIND_ORDER: EventKind[] = [
  'tournament', 'festival', 'camp', 'seminar', 'lecture', 'other',
];
