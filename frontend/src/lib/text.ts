/** Мелкая текстовая работа над данными календаря: место и оружие одной строкой. */

const normalize = (value: string) => value.toLowerCase().replace(/ё/g, 'е');

/**
 * Место одной строкой — практически всегда город.
 *
 * С 06.11.2026 адрес в данные календаря не попадает вовсе (решение заказчика «оставь только
 * город, не бери улицу-дом»): импорт берёт площадку, только пока города нет — «Калужская
 * область» у выездных лагерей (scripts/calendar_data.py, place_for; проверяется валидацией).
 * Так что на практике здесь или город, или одинокая площадка.
 *
 * Склейку и защиту от дублей («Калуга» + «Калуга», «Краснодар» + «г. Краснодар ул. Красная
 * 43/1» — обе строки приезжали из портала разом) оставляем страховкой на случай, когда в
 * данных снова окажется пара: показать «Калуга, Калуга» хуже, чем лишние три строки кода.
 */
export function formatPlace(city: string | null | undefined, locationManual: string | null | undefined): string {
  const left = (city ?? '').trim();
  const right = (locationManual ?? '').trim();
  if (!left) return right;
  if (!right) return left;
  if (normalize(right).includes(normalize(left))) return right;
  return `${left}, ${right}`;
}

/**
 * Место для ленты на телефоне: короткое имя города и больше ничего. Уточнение места («Лужники»,
 * адрес зала) сюда не идёт — в однодневном баре на 375px плашке достаётся 116 точек, и полный
 * «Санкт-Петербург» съедал из них 85: названию турнира не оставалось ничего ни при каком шрифте
 * (замер 11.11.2026, docs/Calendar.md §5ж).
 *
 * Короткой формы может не быть: город не из справочника или место задано одной строкой без
 * города. Тогда показываем то, что есть, — пустое место хуже длинного.
 */
export function shortPlace(cityShort: string | null | undefined, place: string): string {
  return (cityShort ?? '').trim() || place;
}

/**
 * Сколько БУКВ имени города помещается в колонку даты списка (60px, шрифт 10px).
 *
 * Замер 12.11.2026 по всем 195 городам справочника: самое широкое девятибуквенное имя —
 * «Дзержинск», 55.9 точки, а десятибуквенное «Домодедово» уже 63.3 и в колонку не входит.
 * Считать буквы, а не точки, приходится потому, что ширину на сборке не измерить: страница
 * рисуется заранее, браузера там нет. Девять — это не «примерно», а последняя длина, у которой
 * в колонку влезает ЛЮБОЕ имя справочника, а не только узкое: «Красноярск» (10 букв, 58.9)
 * влез бы, но правило по буквам не умеет отличать его от «Домодедово».
 *
 * Меняется колонка или шрифт — число надо перемерить, иначе длинные имена начнут обрываться.
 */
export const CITY_FITS_DATE_COLUMN = 9;

/**
 * Город для колонки даты в списке: полное имя, пока оно в колонку влезает, и короткая форма
 * у тех, кто не влезает («Санкт-Петербург» → «СПб», «Ростов-на-Дону» → «РнД»).
 *
 * Сокращение здесь — цена за узкую колонку, а не самоцель (просьба заказчика 12.11.2026:
 * «резать только самые длинные»). На сегодняшних данных полным именем показываются 276 событий
 * из 410 с городом, сокращением — 134.
 */
export function placeForDateColumn(
  city: string | null | undefined,
  cityShort: string | null | undefined,
  place: string,
): string {
  const full = (city ?? '').trim();
  if (full && full.length <= CITY_FITS_DATE_COLUMN) return full;
  return shortPlace(cityShort, place);
}

type NominationLike = { weapon: string; weaponCode: string | null };

/**
 * Оружие турнира для строки списка. Распознанное оружие (у номинации есть код) вытесняет
 * нераспознанный текст: источники пишут в поле оружия что угодно — «longsword - women»,
 * «advanced», «mixed», — и вперемешку с нормальными названиями это выглядит как мусор. Если
 * распознанного нет вовсе, показываем текст как есть: потерять номинацию хуже, чем показать
 * сырую строку.
 */
export function weaponSummary(nominations: readonly NominationLike[]): string[] {
  const known = [...new Set(nominations.filter((n) => n.weaponCode).map((n) => n.weapon))];
  if (known.length > 0) return known;
  return [...new Set(nominations.map((n) => n.weapon).filter((w) => w && w.trim().length > 0))];
}

/**
 * Организаторы одной строкой. Турнир часто делают вместе два клуба, и второй обязан быть назван —
 * иначе его работу припишут первому. Соединяется по-русски («А и Б», «А, Б и В»), а не запятыми:
 * это читают люди, а не разбирает машина.
 */
export function formatOrganizers(
  organizerName: string | null | undefined,
  coOrganizers?: readonly string[],
): string {
  const names = [organizerName, ...(coOrganizers ?? [])]
    .map((name) => (name ?? '').trim())
    .filter(Boolean);
  if (names.length === 0) return '';
  if (names.length === 1) return names[0];
  return `${names.slice(0, -1).join(', ')} и ${names[names.length - 1]}`;
}
